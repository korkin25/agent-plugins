"""Согласование существительного с числом: «1 файл», «3 файла», «11 файлов».

    python3 plural.py 21 файл файла файлов     # печатает: 21 файл

Три формы слова передаются в порядке (одна, несколько, много); для слова «файл» это файл, файла, файлов.
Форма выбирается по последним двум цифрам числа n, знак числа не важен:
  * «одна» — n оканчивается на 1, но не на 11: 1, 21, 101, 1001;
  * «несколько» — n оканчивается на 2, 3 или 4, но не на 12, 13 или 14: 2, 23, 104;
  * «много» — все остальные n: 0, 5–20, 25, 111, 112, 1000.
Если первый аргумент не целое число, утилита печатает `ошибка: ...` в stderr и завершается с кодом 1;
при неверном числе аргументов печатает строку использования и завершается с кодом 2.
"""
import sys


def choose_form(n: int, forms: tuple[str, str, str]) -> str:
    """Вернуть ту из форм (одна, несколько, много), что согласуется с целым числом n."""
    n = abs(n) % 100
    if n % 10 == 1 and n != 11:
        return forms[0]
    if 2 <= n % 10 <= 4 and not 12 <= n <= 14:
        return forms[1]
    return forms[2]


def phrase(n: int, forms: tuple[str, str, str]) -> str:
    """Число и согласованное слово: phrase(5, ("файл", "файла", "файлов")) == "5 файлов"."""
    return f"{n} {choose_form(n, forms)}"


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print("использование: plural.py ЧИСЛО ОДНА НЕСКОЛЬКО МНОГО", file=sys.stderr)
        return 2
    try:
        n = int(argv[0])
    except ValueError:
        print(f"ошибка: {argv[0]!r} — не целое число", file=sys.stderr)
        return 1
    print(phrase(n, (argv[1], argv[2], argv[3])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
